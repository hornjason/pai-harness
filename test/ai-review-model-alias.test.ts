/**
 * #685 AC-6 — no bare model-family alias reaches the generated review job.
 *
 * A bare family alias re-points at a different model the day the alias moves,
 * so the gate a consumer measured is not the gate they keep, and nothing in
 * the workflow says it changed. An exact identifier is the only thing that
 * pins; an alias is a promise somebody else can edit.
 *
 * ## What this file does NOT cover, and why it is not hidden here
 *
 * AC-5 — "the generated job hands the review action exactly one exact pinned
 * model identifier, declared once and interpolated into `claude_args`" — is
 * **not implemented**, because there is nothing yet to hand it to.
 * `buildReviewRunScript()` is a placeholder whose own text says *"no review
 * step is wired into this job yet (#631)"*: there is no review action, no
 * `claude_args`, and no model input. #685's own Dependencies section says
 * Phase 1 must land first, and #631 is open.
 *
 * So this is AC-6 standing alone, and it is deliberately the half that is
 * useful FIRST. A guard that exists before the model does is a guard Phase 1
 * has to get past; the same guard added afterwards is one that ratifies
 * whatever Phase 1 happened to write.
 *
 * ## The trap this guard is one character away from
 *
 * The cheapest way to make "no alias appears" true is to refuse the family
 * word outright. That passes today — the generated workflow contains no model
 * at all — and it makes Phase 1 **impossible**, because `claude-opus-5-5`
 * contains `opus`. A guard that blocks the fix it exists to protect is worse
 * than no guard, and it would look identical in a green suite.
 *
 * AC-6c is the case that stops it: an exact pinned identifier must NOT be a
 * violation. Without it, `modelAliasViolations` could be `/opus|sonnet|haiku/`
 * and every other case here would still be green.
 *
 * ## Why the guard is run against generated bytes, not a string in this file
 *
 * A scan reporting "no alias found" over text nobody produced is
 * indistinguishable from a scan that read nothing
 * (`.claude/rules/checks-must-be-able-to-fail.md`). The fixture scaffolds a
 * real project and reads `.github/workflows/ai-review.yml` off disk, and
 * AC-6a asserts the text is non-empty and contains the review job before it
 * asserts anything is absent from it — an empty string contains no aliases.
 */
import { describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";

import {
  AI_REVIEW_JOB,
  MODEL_FAMILY_ALIASES,
  modelAliasScanSlice,
  modelAliasViolations,
} from "../lib/scaffold/ai-review-step";
import { createCiWorkflows } from "../lib/scaffold/steps";

/** Scaffold a real project and return the review workflow it actually wrote. */
function generatedReviewWorkflow(): { text: string; cleanup: () => void } {
  const root = mkdtempSync(join(tmpdir(), "rungate-685-"));
  mkdirSync(join(root, ".github", "workflows"), { recursive: true });
  createCiWorkflows(root, []);
  const text = readFileSync(join(root, ".github", "workflows", "ai-review.yml"), "utf-8");
  return { text, cleanup: () => rmSync(root, { recursive: true, force: true }) };
}

describe("#685 AC-6: the generated review workflow carries no bare alias", () => {
  test("AC-6a: the generated workflow is real, non-empty, and clean", () => {
    const { text, cleanup } = generatedReviewWorkflow();
    try {
      // Establish the subject BEFORE asserting an absence from it. An empty
      // string satisfies every "does not contain" assertion ever written.
      expect(text.length).toBeGreaterThan(200);
      expect(text).toContain(AI_REVIEW_JOB);
      expect(modelAliasViolations(text)).toEqual([]);
    } finally { cleanup(); }
  });

  test("AC-6b: an alias planted into the generated text turns the guard red", () => {
    // The mutation performed in-tree rather than promised in a commit message.
    // Each family is planted separately: a guard that caught one and not the
    // others would be green on a single-family case.
    const { text, cleanup } = generatedReviewWorkflow();
    try {
      for (const alias of MODEL_FAMILY_ALIASES) {
        // A VALUE position, deliberately — not a comment. The first draft of
        // this case planted `# model: <alias>`, and when the guard learned to
        // skip comments (because a correct pin documents itself by naming the
        // alias it avoids) that plant would have gone quiet while still
        // reading like a mutation. A case that stops witnessing because the
        // code improved is the #507 shape.
        const planted = text.replace(`jobs:`, `jobs:\n  probe:\n    env:\n      ANTHROPIC_MODEL: ${alias}`);
        expect(planted, `the plant did not change the text for ${alias}`).not.toBe(text);
        const found = modelAliasViolations(planted);
        expect(found.length, `a bare '${alias}' was not caught`).toBeGreaterThan(0);
        // The token, not a count: "1 violation" sends nobody to a line.
        expect(found.join(" ")).toContain(alias);
      }
    } finally { cleanup(); }
  });

  test("AC-6c: an EXACT pinned identifier is not a violation", () => {
    // The case that stops the cheapest wrong fix. Without it the guard could
    // be a bare family-word search, which passes today and makes Phase 1's
    // actual job — pinning an exact model — permanently unshippable.
    for (const alias of MODEL_FAMILY_ALIASES) {
      const pinned = `          claude_args: --model claude-${alias}-5-5\n`;
      expect(modelAliasViolations(pinned), `claude-${alias}-5-5 was refused as an alias`).toEqual([]);
    }
  });

  test("AC-6d: a family word is caught wherever it sits, not only after 'model:'", () => {
    // A detector narrower than what it detects. Keying on `model:` means an
    // alias reaching the action through `claude_args`, an env var or a
    // composite flag walks past.
    for (const probe of [
      `  CLAUDE_MODEL: sonnet\n`,
      `  run: claude --model opus\n`,
      `  args: ["--model", "haiku"]\n`,
    ]) {
      expect(modelAliasViolations(probe).length, `missed: ${probe.trim()}`).toBeGreaterThan(0);
    }
  });

  test("AC-6e: the alias list is non-empty and each entry is load-bearing", () => {
    // An empty population agrees with every rule. Three families, and each
    // one is independently detected — asserted, not assumed from the list.
    expect(MODEL_FAMILY_ALIASES.length).toBeGreaterThanOrEqual(3);
    for (const alias of MODEL_FAMILY_ALIASES) {
      expect(modelAliasViolations(`  model: ${alias}\n`).length).toBeGreaterThan(0);
    }
  });

  test("AC-6g: a comment may name an alias; a value on the same line still cannot", () => {
    // The boundary of the comment-stripping, asserted rather than described.
    // Narrowing a detector is the change most likely to buy green with
    // blindness, so both directions are pinned here.
    //
    // The left-hand case is not hypothetical: `.github/workflows/
    // claude-review.yml` pins `claude-sonnet-5` at its one value position and
    // explains why in a comment that necessarily names the alias. Scanning
    // the whole document reported that file as two violations, both of them
    // the documentation of the fix.
    expect(modelAliasViolations(`# unpinned, the opus alias resolves to Opus 5.5 and bills at that rate\n`)).toEqual([]);
    expect(modelAliasViolations(`  ANTHROPIC_MODEL: sonnet  # pinned? no\n`).length).toBeGreaterThan(0);

    // And the slice must not be empty, or every absence above is vacuous.
    const slice = modelAliasScanSlice(`  ANTHROPIC_MODEL: claude-sonnet-5  # a comment\n`);
    expect(slice.trim().length).toBeGreaterThan(0);
    expect(slice).toContain("claude-sonnet-5");
    expect(slice).not.toContain("a comment");
  });

  test("AC-6h: every committed workflow in this repo passes the guard", () => {
    // The generator test cannot see a hand-edit, and `claude-review.yml` is
    // hand-authored. Its exact pin at `ANTHROPIC_MODEL: claude-sonnet-5` is
    // what this must accept while still refusing a bare family word.
    const dir = join(import.meta.dir, "..", ".github", "workflows");
    const files = readdirSync(dir).filter(f => /\.ya?ml$/.test(f));
    expect(files.length, "no workflow files found — the scan read nothing").toBeGreaterThan(3);
    const offenders: string[] = [];
    for (const f of files) {
      const v = modelAliasViolations(readFileSync(join(dir, f), "utf-8"));
      if (v.length > 0) offenders.push(`${f}: ${[...new Set(v)].join(", ")}`);
    }
    expect(offenders, `bare model aliases in committed workflows:\n${offenders.join("\n")}`).toEqual([]);
  });

  test("AC-6f: ordinary prose that merely contains the letters is not a violation", () => {
    // The inverse of AC-6d, and the reason the guard tokenises instead of
    // substring-matching. A false refusal on a word like "opusculum" would be
    // a guard people learn to switch off.
    expect(modelAliasViolations(`  # see the opusculum for rationale\n`)).toEqual([]);
    expect(modelAliasViolations(`  name: sonnets-and-haikus\n`)).toEqual([]);
  });
});
