/**
 * A real primary checkout, a real linked worktree, and the generated
 * pre-commit hook EXECUTED in one of them (#450, #599, #610).
 *
 * Shared by `test/unit/git-hooks-generator.test.ts`,
 * `test/unit/git-hooks-worktree-mutation.test.ts` and
 * `test/unit/pre-commit-updater-resolution.test.ts` so that every battery and
 * every in-tree case observes the hook through the SAME fixture. Two
 * hand-written copies of a fixture are two things that can drift, and a
 * battery measured through a fixture that differs from the one the cases use
 * is measuring a hook nobody ships.
 *
 * The three readings this exposes are deliberately distinct, because the
 * defects they catch are distinct:
 *
 *   - `staged`   — what the hook put in the index. The old hook staged
 *                  whatever was on disk whether or not anything regenerated
 *                  it, so staging ALONE is not evidence the updater ran.
 *   - `stateMd`  — the bytes of PROJECT-STATE.md afterwards. This is the
 *                  evidence the updater ran, and WHICH updater ran: the two
 *                  planted copies write different bytes (#610), because a
 *                  fixture whose two candidates are interchangeable cannot
 *                  witness a fix about choosing between them.
 *   - `out`/`err`— kept APART. A concatenated reading cannot tell which
 *                  stream carried a message, so an assertion over it holds
 *                  whichever stream it was on, which is the whole of AC-3.
 */
import { execFileSync } from "child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { createGitHooks } from "../../lib/scaffold/steps";

/** What the DA last wrote. Present before the hook runs, in every layout. */
export const ORIGINAL = "# state as the DA last wrote it\n";

/** Written only by `scripts/update-project-state.ts`. */
export const REGENERATED_BY_SCRIPTS = "# regenerated by scripts/update-project-state.ts\n";

/** Written only by `node_modules/rungate/scripts/update-project-state.ts`. */
export const REGENERATED_BY_VENDORED =
  "# regenerated by node_modules/rungate/scripts/update-project-state.ts\n";

/** The fixture updater's own stdout, so the hook's handling of it is visible. */
export const UPDATER_CHATTER = "update-project-state: rebuilding";

/**
 * Where the updater lives and what the tree declares itself to be — which
 * together are the whole of #599 and #610.
 *
 * `harness` is this repository's shape: a `package.json` naming rungate, a
 * `scripts/update-project-state.ts`, and no `node_modules/rungate`.
 * `vendored` is an ordinary consumer. `none` is the reading the pre-#599 hook
 * could not produce, and `failing` is the one it threw away.
 *
 * The two DUAL layouts are #610's subject and neither existed before it. A
 * consumer that happens to keep a script at `scripts/update-project-state.ts`
 * and a harness checkout that happens to carry a vendored duplicate are two
 * of the three trees on which the filename sniff and the generation-time
 * resolution give different answers — without them the fix cannot be told
 * from the defect.
 *
 * `consumer-own-only` is the third, and it exists because every other fixture
 * here holds a precondition: SOME copy rungate installed is present. A
 * consumer whose only updater is its own is on the other side of that
 * precondition, and a battery whose fixtures all meet one measures nothing
 * past it (`.claude/rules/checks-must-be-able-to-fail.md`). It was added
 * after a mutation row came back HIGH and the extra red turned out to be a
 * text assertion standing in for a behaviour nothing drove.
 */
export type UpdaterLayout =
  | "harness"
  | "vendored"
  | "consumer-with-own"
  | "consumer-own-only"
  | "harness-with-vendored"
  | "failing"
  | "none";

export interface HookRun {
  code: number;
  out: string;
  err: string;
  staged: string[];
  stateMd: string;
}

function okUpdater(writes: string): string {
  return [
    'import { writeFileSync } from "fs";',
    `console.log(${JSON.stringify(UPDATER_CHATTER)});`,
    `writeFileSync("PROJECT-STATE.md", ${JSON.stringify(writes)});`,
    "",
  ].join("\n");
}

const FAILING_UPDATER = [
  'console.error("update-project-state: could not read the issue list");',
  "process.exit(3);",
  "",
].join("\n");

/** True for the layouts whose package.json declares the rungate harness. */
const DECLARES_HARNESS: Record<UpdaterLayout, boolean> = {
  harness: true,
  "harness-with-vendored": true,
  failing: true,
  vendored: false,
  "consumer-with-own": false,
  "consumer-own-only": false,
  none: false,
};

function writeScriptsCopy(root: string, body: string): void {
  mkdirSync(join(root, "scripts"), { recursive: true });
  writeFileSync(join(root, "scripts", "update-project-state.ts"), body);
}

function writeVendoredCopy(root: string): void {
  const dir = join(root, "node_modules", "rungate", "scripts");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "update-project-state.ts"), okUpdater(REGENERATED_BY_VENDORED));
}

/**
 * Plant the layout: the package.json that declares the tree's identity, and
 * whichever updater copies the layout names.
 *
 * Used for BOTH the root a hook is generated against and the repository it is
 * then executed in, so a hook's baked path and the file it finds at commit
 * time come from one description rather than two.
 */
export function plantLayout(root: string, layout: UpdaterLayout): void {
  mkdirSync(root, { recursive: true });
  writeFileSync(
    join(root, "package.json"),
    JSON.stringify({ name: DECLARES_HARNESS[layout] ? "rungate" : "a-consumer" }, null, 2) + "\n",
  );
  if (layout === "none") return;
  if (layout === "failing") {
    writeScriptsCopy(root, FAILING_UPDATER);
    return;
  }
  if (
    layout === "harness" ||
    layout === "consumer-with-own" ||
    layout === "consumer-own-only" ||
    layout === "harness-with-vendored"
  ) {
    writeScriptsCopy(root, okUpdater(REGENERATED_BY_SCRIPTS));
  }
  if (layout === "vendored" || layout === "consumer-with-own" || layout === "harness-with-vendored") {
    writeVendoredCopy(root);
  }
}

/**
 * The hook the generator emits for a tree of this shape.
 *
 * Driven through `createGitHooks` — the thing a scaffold run actually calls —
 * rather than through the template function, so a fix that lands in the
 * template and never reaches the caller is still red here. (#431, #235 and
 * #224 are all that zero.)
 *
 * Built against a throwaway root carrying the layout, so nothing in this
 * repository — least of all the shared `.git/hooks/pre-commit` that every
 * worktree on the machine runs — is read or written to produce it.
 */
export function hookFor(layout: UpdaterLayout): string {
  const root = mkdtempSync(join(tmpdir(), "rungate-hookgenroot-"));
  try {
    plantLayout(root, layout);
    mkdirSync(join(root, ".git", "hooks"), { recursive: true });
    createGitHooks(root, []);
    return readFileSync(join(root, ".git", "hooks", "pre-commit"), "utf-8");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

/**
 * Run `script` as the pre-commit hook in a primary checkout or in a linked
 * worktree cut from it, with the DA-owned state files present and UNSTAGED.
 *
 * Nothing but the hook's own `git add` can put them in the index, so an empty
 * `staged` is a measurement rather than a default.
 */
export function runWithStateFiles(
  script: string,
  where: "primary" | "worktree",
  opts: { updater?: UpdaterLayout } = {},
): HookRun {
  const layout = opts.updater ?? "harness";
  const primary = mkdtempSync(join(tmpdir(), "rungate-wtstate-"));
  const linked = `${primary}-linked`;
  try {
    execFileSync("git", ["init", "-q", "-b", "main"], { cwd: primary });
    execFileSync("git", ["config", "user.email", "t@example.com"], { cwd: primary });
    execFileSync("git", ["config", "user.name", "T"], { cwd: primary });
    writeFileSync(join(primary, "seed.txt"), "seed\n");
    execFileSync("git", ["add", "-A"], { cwd: primary });
    execFileSync("git", ["commit", "-q", "--no-verify", "-m", "seed"], { cwd: primary });
    execFileSync("git", ["worktree", "add", "-q", "-b", "side", linked], { cwd: primary });

    const cwd = where === "primary" ? primary : linked;
    writeFileSync(join(cwd, "project-state.json"), '{"session": 1}\n');
    writeFileSync(join(cwd, "PROJECT-STATE.md"), ORIGINAL);
    writeFileSync(join(cwd, "SUCCESS.md"), "# success\n");
    plantLayout(cwd, layout);

    const sh = join(cwd, ".pre-commit.sh");
    writeFileSync(sh, script, { mode: 0o755 });
    // stderr goes to a FILE rather than to the pipe, because execFileSync
    // only hands stderr back on a throw — and the runs this fixture cares
    // most about are the ones that exit 0. Reading the two streams from one
    // execution is the point: re-running the hook to get the other stream
    // would double every side effect it has.
    const errFile = join(cwd, ".pre-commit.err");
    let code = 0;
    let out = "";
    try {
      out = execFileSync("sh", ["-c", '"$0" 2>"$1"', sh, errFile], {
        cwd,
        encoding: "utf-8",
        stdio: ["pipe", "pipe", "pipe"],
      });
    } catch (e: any) {
      code = e.status ?? -1;
      out = String(e.stdout ?? "");
    }
    const err = readFileSync(errFile, "utf-8");
    rmSync(errFile, { force: true });
    const staged = execFileSync("git", ["diff", "--cached", "--name-only"], {
      cwd,
      encoding: "utf-8",
    })
      .split("\n")
      .filter(Boolean);
    const stateMd = readFileSync(join(cwd, "PROJECT-STATE.md"), "utf-8");
    return { code, out, err, staged, stateMd };
  } finally {
    rmSync(linked, { recursive: true, force: true });
    rmSync(primary, { recursive: true, force: true });
  }
}
